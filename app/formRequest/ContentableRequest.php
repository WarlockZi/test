<?php

namespace app\formRequest;

use app\formRequest\baseFormRequests\FormRequest1;
use app\service\AuthService\AuthService;
use Predis\Command\Redis\AUTH;

class ContentableRequest extends FormRequest1
{

    public function rules(): array
    {
        return [
            'model' => 'required|string',
            'id' => 'required|integer',
            'field' => 'sometimes|string',
            'relation' => 'sometimes|array',
        ];
    }

    public function messages(): array
    {
        return [
            'model.required' => 'field is required',
            'model.string' => 'field must be string',

            'id.required' => 'id is required',
            'id.integer' => 'id must be integer',

            'field' => 'field must be string',

            'relation' => 'relation должно быть array',

        ];
    }
    public function authorize(): bool
    {
        return AuthService::getUser()->isAdmin(); // TODO: Change the autogenerated stub
    }

}